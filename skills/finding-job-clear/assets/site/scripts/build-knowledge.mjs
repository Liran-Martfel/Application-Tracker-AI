// Splits knowledge/*.md into chunks (one per heading) and writes src/knowledge.js.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
const dir = new URL('../knowledge/', import.meta.url);
const chunks = [];
for (const f of readdirSync(dir).filter((x) => x.endsWith('.md')).sort()) {
  const source = f.replace(/\.md$/, '');
  let title = '', buf = [];
  for (const line of [...readFileSync(new URL(f, dir), 'utf8').split(/\r?\n/), '## ']) {
    if (line.startsWith('#')) {
      const text = buf.join('\n').trim();
      if (text) chunks.push({ source, title, text });
      title = line.replace(/^#+\s*/, '').trim(); buf = [];
    } else buf.push(line);
  }
}
const hash = createHash('sha256').update(JSON.stringify(chunks)).digest('hex').slice(0, 16);
writeFileSync(new URL('../src/knowledge.js', import.meta.url), `// Generated by scripts/build-knowledge.mjs — do not edit.\nexport const KNOWLEDGE_HASH = ${JSON.stringify(hash)};\nexport const CHUNKS = ${JSON.stringify(chunks, null, 1)};\n`);
console.log(`knowledge: ${chunks.length} chunks, hash ${hash}`);
